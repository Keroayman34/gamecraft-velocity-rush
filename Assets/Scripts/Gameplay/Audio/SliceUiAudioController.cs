using UnityEngine;

namespace VelocityRush.Gameplay
{
    /// <summary>
    /// Plays the scoped slice UI/race stings: countdown ticks, the go signal, pause/resume
    /// feedback, and the finish sting (T-7.11).
    /// </summary>
    /// <remarks>
    /// <para>
    /// All clips are optional serialized references: a missing clip is silent rather than an
    /// error, so the slice still runs before the audio assets are (re)generated.
    /// </para>
    /// <para>
    /// The pool ignores <see cref="AudioListener.pause"/> so the pause sting is audible on the
    /// same frame the simulation freezes. Clip playback never allocates; the event subscriptions
    /// happen once per enable.
    /// </para>
    /// </remarks>
    [DisallowMultipleComponent]
    public sealed class SliceUiAudioController : MonoBehaviour
    {
        private const int UiPoolSize = 4;

        [Header("Scene wiring")]
        [SerializeField] private RaceController race;

        [Header("Clips (generated by the slice audio kit)")]
        [SerializeField] private AudioClip countdownBeep;
        [SerializeField] private AudioClip countdownGo;
        [SerializeField] private AudioClip pauseBeep;
        [SerializeField] private AudioClip resumeBeep;
        [SerializeField] private AudioClip finishSting;

        [Header("Levels")]
        [SerializeField, Range(0f, 1f)] private float countdownVolume = 0.55f;
        [SerializeField, Range(0f, 1f)] private float goVolume = 0.7f;
        [SerializeField, Range(0f, 1f)] private float pauseVolume = 0.45f;
        [SerializeField, Range(0f, 1f)] private float finishVolume = 0.75f;

        private AudioSourcePool _pool;
        private bool _subscribed;
        private RaceState _previousState;
        private int _lastCountdownSeconds = int.MinValue;

        private void Awake()
        {
            _pool = new AudioSourcePool(
                transform,
                "UiStingPool",
                UiPoolSize,
                spatial: false,
                ignoreListenerPause: true);
        }

        private void OnEnable()
        {
            if (race == null)
            {
                return;
            }

            race.RaceFinished += HandleRaceFinished;
            race.PausedChanged += HandlePausedChanged;
            _subscribed = true;
            _previousState = race.State;
            _lastCountdownSeconds = int.MinValue;
        }

        private void OnDisable()
        {
            if (_subscribed && race != null)
            {
                race.RaceFinished -= HandleRaceFinished;
                race.PausedChanged -= HandlePausedChanged;
            }

            _subscribed = false;
            _pool?.StopAll();
        }

        private void Update()
        {
            if (race == null)
            {
                return;
            }

            var state = race.State;

            if (state == RaceState.Countdown)
            {
                var seconds = SliceHudModel.CountdownSeconds(state, race.CountdownRemainingSeconds);
                if (seconds > 0 && seconds != _lastCountdownSeconds)
                {
                    _lastCountdownSeconds = seconds;
                    _pool.Play(countdownBeep, countdownVolume);
                }
            }

            if (_previousState == RaceState.Countdown && state == RaceState.Running)
            {
                _pool.Play(countdownGo, goVolume);
            }

            _previousState = state;
        }

        private void HandlePausedChanged(bool paused)
        {
            _pool.Play(paused ? pauseBeep : resumeBeep, pauseVolume);
        }

        private void HandleRaceFinished(RaceResult result)
        {
            _pool.Play(finishSting, finishVolume);
        }
    }
}
